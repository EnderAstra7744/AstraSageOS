#!/usr/bin/env python3
"""Generates sys/seed_logo.h: the default neofetch logo as a small PNG (/bin/neofetch/custom_logo/astrasage.png)."""
import io, sys
from PIL import Image
from collections import deque
src = Image.open('assets/boot_logo.bmp').convert('RGBA')
W, H = src.size
px = src.load()
seen = set(); q = deque()
for x in range(W):
    q.append((x, 0)); q.append((x, H - 1))
for y in range(H):
    q.append((0, y)); q.append((W - 1, y))
while q:                                   # the black frame around the logo (connected to the border) becomes transparent
    x, y = q.popleft()
    if (x, y) in seen or not (0 <= x < W and 0 <= y < H): continue
    r, g, b, a = px[x, y]
    if r > 40 or g > 40 or b > 40: continue
    seen.add((x, y)); px[x, y] = (0, 0, 0, 0)
    q.extend(((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)))
im = src.resize((48, 48), Image.LANCZOS)
alpha = im.getchannel('A').point(lambda v: 255 if v > 128 else 0)
pal = im.convert('RGB').quantize(15)                       # 15 colours + index 15 = transparent
out = pal.copy()
opx, apx = out.load(), alpha.load()
for y in range(48):
    for x in range(48):
        if apx[x, y] == 0: opx[x, y] = 15
im = out
im.info['transparency'] = 15
buf = io.BytesIO(); im.save(buf, 'PNG', optimize=True, transparency=15, bits=4)
d = buf.getvalue()
with open('sys/seed_logo.h', 'w') as f:
    f.write('/* generated by sys/tools/gen_seed_logo.py - do not edit */\nstatic const unsigned char seed_logo_png[] = {')
    f.write(','.join(str(b) for b in d))
    f.write('};\n')
import re
logo = re.findall(r'"((?:[^"\\]|\\.)*)"', open('terminal/logo.h').read().split('as_logo[] = {')[1].split('};')[0])
lines = []
for l in logo:
    l = re.sub(r'\\033\[[0-9;]*m', '', l).replace('\\\\', '\\').replace('\\"', '"')
    lines.append(l)
with open('sys/seed_logo.h', 'a') as f:
    f.write('static const char seed_logo_txt[] =\n')
    for l in lines:
        f.write('    "' + l.replace('\\', '\\\\').replace('"', '\\"') + '\\n"\n')
    f.write('    "";\n')
print(len(d), 'bytes')
