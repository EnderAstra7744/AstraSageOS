#!/usr/bin/env python3
"""Generates packages/FroggyCode/src/art.as: Froggy's pixel maps, converted from the original Froggy HTML/SVG
(front view with its mouth/eye states, and the side view with the laptop for the 'code' scene).
Run it only when the mascot changes:  python3 sys/tools/mkfroggyart.py <froggy.html>"""
import re, sys, os

html = open(sys.argv[1], encoding="utf-8").read()
body = html[html.index('<g id="frogBody">'):html.index('<!-- yan dönmüş')]
PAL = {'#1F3D2B': '0', '#5BBF5A': '1', '#8BE07A': '2', '#EAF6C9': '3', '#F28B82': '4', '#fff': '5', '#FFFFFF': '5'}


def front(hide, lids=False, pupil_dy=0):
    b = body
    for gid in ('mouthOpen', 'mouthFlat', 'mouthSmile'):
        if gid in hide:
            b = re.sub(r'<g id="%s".*?</g>' % gid, '', b, flags=re.S)
    if not lids:
        b = re.sub(r'<g class="lid">.*?</g>', '', b, flags=re.S)
    g = [['.'] * 16 for _ in range(13)]
    fill = None
    in_pupil = False
    for m in re.finditer(r'<g class="pupil">|<g fill="([^"]+)">|</g>|<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)"(?: fill="([^"]+)")?', b):
        t = m.group(0)
        if t == '<g class="pupil">': in_pupil = True; continue
        if m.group(1): fill = m.group(1); continue
        if t == '</g>': in_pupil = False; continue
        x, y, w, h = map(int, m.group(2, 3, 4, 5)); f = m.group(6) or fill
        if in_pupil: y += pupil_dy
        for yy in range(y, y + h):
            for xx in range(x, x + w): g[yy][xx] = PAL[f]
    return [''.join(r) for r in g]


SMILE = front(('mouthOpen', 'mouthFlat'))
OPEN = front(('mouthSmile', 'mouthFlat'))
FLAT = front(('mouthSmile', 'mouthOpen'))
BLINK = front(('mouthOpen', 'mouthFlat'), lids=True)
UP = front(('mouthSmile', 'mouthOpen'), pupil_dy=-1)        # thinking: pupils look up (outline drawn over them)

# the sitting frog from the HTML (SIDE) and the laptop (LAP)
SIDE = ['.......OOO.OOO..', '......OWWWOWWWO.', '......OWPWOWPWO.', '....OOOWPPOWPPOO', '...OGGLLGGGGGGGO',
        '..OGGGGGGGGGGGGO', '.OGGGGGGGGOGGGGO', '.OGGGGGGRRGOOOOO', '.OGGOOOGGGGGGGGO', '.OGOLLLOGGGBBBBO',
        '.OGOLLLOGGGBBBBO', '.OGOOOOOGGGBBBO.', '..OOOOOOOOOOOO..']
LAP = ['........OOO', '.....OOOSSO', '..OOOSSSSSO', '..OSSSSSSSO', '..OSSSSSSSO', '..OSSSSSOOO', '..OSSOOODKD', '..OOODKDKDK', 'EDKDKDKDKDE']
SP = {'O': '0', 'G': '1', 'L': '2', 'B': '3', 'W': '5', 'P': '0', 'R': '4'}
LP = {'O': '6', 'S': '7', 'D': '8', 'K': '9', 'E': '0'}
W = 26
grid = [['.'] * W for _ in range(13)]
for y, r in enumerate(SIDE):
    for x, c in enumerate(r):
        if c != '.': grid[y][x] = SP[c]
for y, r in enumerate(LAP):
    for x, c in enumerate(r):
        if c != '.': grid[y + 4][x + 15] = LP[c]
CODE_SCENE = [''.join(r) for r in grid]
# the frog's eyes in the sitting view blink too: lids over the two eyes (x 7..9 and 11..13, rows 1..3)
CODE_BLINK = [list(r) for r in CODE_SCENE]
for x in (7, 11):
    for y in (1, 2, 3):
        for xx in range(x, x + 3):
            CODE_BLINK[y][xx] = '1'
    for xx in range(x, x + 3):
        CODE_BLINK[2][xx] = '0'
CODE_BLINK = [''.join(r) for r in CODE_BLINK]

out = []
P = out.append
P("@ FroggyCode art - generated by sys/tools/mkfroggyart.py from the original Froggy pixel art. Palette 0-9, a-e:")
P("@ 0 ink 1 green 2 light 3 belly 4 cheek 5 white 6-9 laptop a-e code colours")


def rows_call(prefix, rows, per, start=0):
    lines = []
    for i in range(0, len(rows), per):
        args = ", ".join('"%s"' % r for r in rows[i:i + per])
        lines.append("gui_sprite(fx, fy + %d * fa, fz, %s);" % (start + i, args))
    return lines


def func(name, body):
    P("func %s()" % name)
    P("{")
    for l in body: P(l)
    P("}")


func("pal_init", [
    'gui_pal(0, "#1F3D2B");', 'gui_pal(1, "#5BBF5A");', 'gui_pal(2, "#8BE07A");', 'gui_pal(3, "#EAF6C9");',
    'gui_pal(4, "#F28B82");', 'gui_pal(5, "#FFFFFF");', 'gui_pal(6, "#2B3544");', 'gui_pal(7, "#0F1B14");',
    'gui_pal(8, "#AEB6C2");', 'gui_pal(9, "#6B7480");', 'gui_pal(10, "#FF7EB6");', 'gui_pal(11, "#6BE675");',
    'gui_pal(12, "#6FD3FF");', 'gui_pal(13, "#FFD866");', 'gui_pal(14, "#F2F2F2");'])

# the front view is drawn in three bands so the eyes, mouth and body can change on their own
func("frog_eyes", [
    'if (look == 1)', '{'] + rows_call("", UP[0:4], 4) + ['}', 'else', '{',
    'if (blink > 0)', '{'] + rows_call("", BLINK[0:4], 4) + ['}', 'else', '{'] + rows_call("", SMILE[0:4], 4) + ['}', '}'])
# rows 4..6 and 9..12 do not change
func("frog_body", rows_call("", SMILE[4:7], 3, 4) + [
    'gui_sprite(fx, fy + 9 * fa, fz, "%s", "%s", "%s", "%s");' % tuple(SMILE[9:13])])
func("frog_mouth", [
    'if (mouth == 1)', '{', 'gui_sprite(fx, fy + 7 * fa, fz, "%s", "%s");' % tuple(OPEN[7:9]), '}',
    'if (mouth == 2)', '{', 'gui_sprite(fx, fy + 7 * fa, fz, "%s", "%s");' % tuple(FLAT[7:9]), '}',
    'if (mouth == 0)', '{', 'gui_sprite(fx, fy + 7 * fa, fz, "%s", "%s");' % tuple(SMILE[7:9]), '}'])
func("draw_frog", ['frog_eyes();', 'frog_mouth();', 'frog_body();'])

SPLIT = len(out)
func("draw_scene", [
    'if (blink > 0)', '{'] + rows_call("", CODE_BLINK[0:5], 5) + rows_call("", CODE_BLINK[5:10], 5, 5) + rows_call("", CODE_BLINK[10:13], 3, 10) + ['}', 'else', '{'] +
    rows_call("", CODE_SCENE[0:5], 5) + rows_call("", CODE_SCENE[5:10], 5, 5) + rows_call("", CODE_SCENE[10:13], 3, 10) + ['}'])

# the code lines on the laptop screen appear cell by cell (cells = how many are visible)
CODE = ['ppp ggg', ' ccc ww', ' yy www', 'gggggg ']
COLORS = {'p': '#FF7EB6', 'g': '#6BE675', 'c': '#6FD3FF', 'y': '#FFD866', 'w': '#F2F2F2'}
COL_X = [18, 19, 20, 21, 22, 23, 24]
COL_Y = [7, 7, 6, 6, 6, 5, 5]
cells = []
for row, line in enumerate(CODE):
    for col, ch in enumerate(line):
        if ch != ' ': cells.append((COL_X[col], COL_Y[col] + row, COLORS[ch]))
body = []
for i, (x, y, c) in enumerate(cells):
    body.append('if (cells > %d)' % i)
    body.append('{')
    body.append('gui_rect(fx + %d * fa, fy + %d * fa, fa, fa, "%s");' % (x, y, c))
    body.append('}')
func("draw_cells", body)
P("@ cells in total: %d" % len(cells))
d = os.path.join(os.path.dirname(__file__), '..', '..', 'packages', 'FroggyCode', 'src')
a = "\n".join(out[:SPLIT]) + "\n"
b = "@ FroggyCode: the sitting frog with the laptop (code scene) - generated by sys/tools/mkfroggyart.py\n" + "\n".join(out[SPLIT:]) + "\n"
open(os.path.join(d, 'art.as'), 'w').write(a)
open(os.path.join(d, 'scene.as'), 'w').write(b)
print("bytes:", len(a), len(b))
