def primes(n):
    out=[];k=2
    while len(out)<n:
        if all(k%p for p in out): out.append(k)
        k+=1
    return out
def icbrt(x):
    lo,hi=0,1<<(x.bit_length()//3+2)
    while lo<hi:
        m=(lo+hi+1)//2
        if m**3<=x: lo=m
        else: hi=m-1
    return lo
# SHA-512 K: first 64 bits of fractional part of cube roots of first 80 primes
K512=[]
for p in primes(80):
    c=icbrt(p<<192)          # cbrt(p)*2^64
    K512.append(c & ((1<<64)-1))
H384=[]
for p in primes(16)[8:]:
    s=isqrt(p<<256)          # sqrt(p)*2^128 -> frac64 = (s>>64)&mask
    H384.append((isqrt(p<<128)) & ((1<<64)-1))
