#!/usr/bin/env python3
"""sys/lang/*.tsv (English, Spanish, Russian, Chinese - tab separated) -> sys/lang_tab.h.
Keys are the English texts exactly as they are written in the C source (\\n stays as \\n)."""
import glob, os, sys
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
rows, seen = [], set()
for f in sorted(glob.glob("sys/lang/*.tsv")):
    for n, line in enumerate(open(f, encoding="utf-8").read().split("\n"), 1):
        if not line.strip(): continue
        c = line.split("\t")
        if len(c) == 4: c.append("")
        if len(c) != 5: sys.exit("%s:%d: need 4 (en es ru zh) or 5 (+ tr) tab separated columns" % (f, n))
        if c[0] in seen: sys.exit("%s:%d: duplicate key %r" % (f, n, c[0]))
        seen.add(c[0]); rows.append(c)
with open("sys/lang_tab.h", "w", encoding="utf-8") as o:
    o.write("/* Generated by sys/lang/gen_lang.py from sys/lang/*.tsv - do not edit. English | Spanish | Russian | Chinese. */\n")
    o.write("static const struct { const char *en, *es, *ru, *zh, *tr; } lang_rows[] = {\n")
    for c in rows:
        o.write("    { " + ", ".join('"%s"' % x.replace('"', '\\"') for x in c) + " },\n")
    o.write("};\n#define LANG_NROWS %d\n" % len(rows))
print(len(rows), "rows")
