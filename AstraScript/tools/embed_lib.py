#!/usr/bin/env python3
"""Turns include/lib/*.ash into src/lib_data.c (the built-in module library)."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
lib = os.path.join(here, "..", "include", "lib")
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "src", "lib_data.c")
names = sorted(f for f in os.listdir(lib) if f.endswith(".ash"))
with open(out, "w") as o:
    o.write("/* generated by tools/embed_lib.py - do not edit */\n#include \"as_types.h\"\n")
    for i, n in enumerate(names):
        data = open(os.path.join(lib, n), "rb").read()
        o.write("static const char lib_%d[] = {%s, 0};\n" % (i, ",".join(str(b) for b in data)))
    o.write("const char *const as_lib_names[] = {%s 0};\n" % "".join('"%s", ' % n for n in names))
    o.write("const char *const as_lib_text[] = {%s 0};\n" % "".join("lib_%d, " % i for i in range(len(names))))
